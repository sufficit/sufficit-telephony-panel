const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
 const browser = await chromium.launch({headless:true});
 try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  await page.addInitScript(() => localStorage.setItem('telephony-panel-language-v2','pt-BR'));
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:5169/board?preview=true&acdpreview=waiting';
  const region=page.locator('#board-queue-region');
  await page.goto(base+'&queuesummarypreview=partial');
  await region.locator('.board-tile').first().waitFor();
  assert.equal((await region.locator('.board-totals').innerText()).trim(),'— / 2');
  assert.match(await region.innerText(), /Filas sem estado atual: 1/);
  assert.match(await region.getByRole('status').innerText(), /Total em espera indisponível/);
  assert.equal(await region.locator('.board-tile').count(),3);
  assert.match(await region.locator('.board-tile').last().innerText(),/0000006500/);
  const queue = region.locator('.board-tile').filter({hasText:'Homologação Sufficit'});
  assert.equal(await queue.count(),1);
  assert.match(await queue.innerText(), /2 antes do atendimento/);
  assert.match(await queue.innerText(), /6007/);
  assert.match(await queue.innerText(), /6008/);
  assert.equal(await queue.locator('.tile-node').count(),0);
  await queue.click();
  const dialog=page.getByRole('dialog'); await dialog.waitFor();
  assert.match(await dialog.innerText(),/11111111-1111-7111-8111-111111116599/);
  assert.equal(await dialog.locator('tbody tr').count(),2);
  assert.match(await dialog.innerText(), /SIP\/0000006007-000000ef/);
  assert.match(await dialog.innerText(), /SIP\/0000006008-000000ee/);
  assert.match(await dialog.innerText(),/google-voip/);
  assert.match(await dialog.innerText(),/apoint-voip/);
  assert.match(await dialog.getByRole('link',{name:'Gerenciar esta fila no Blazor'}).getAttribute('href'), /queueid=11111111111171118111111111116599/);
  await page.keyboard.press('Escape'); await dialog.waitFor({state:'detached'});
  await page.goto(base+'&queuesummarypreview=partial&node=apoint-voip');
  await region.locator('.board-tile').first().waitFor();
  assert.equal(await region.locator('.board-tile').count(),1);
  assert.match(await region.locator('.board-tile').innerText(), /1 antes do atendimento/);
  assert.match(await region.locator('.board-tile').innerText(), /6008/);
  assert.doesNotMatch(await region.locator('.board-tile').innerText(), /6007/);
  await page.goto(base+'&queuesummarypreview=partial'); await queue.waitFor();
  fs.mkdirSync('.impeccable/review',{recursive:true});
  await region.screenshot({path:'.impeccable/review/queue-summary-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await region.scrollIntoViewIfNeeded();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'.impeccable/review/queue-summary-mobile.png'});
  await page.goto(base); await region.locator('.board-tile').first().waitFor();
  assert.match(await region.locator('.board-totals').innerText(),/^\d+ \/ 2$/);
  assert.equal(await region.getByRole('status').count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS queue summary: partial coverage, distinct native replicas, retained history, current-first order, complete coverage and mobile overflow');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
